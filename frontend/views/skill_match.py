import html

import streamlit as st

from frontend.common import (
    call, display_skill, donut, get_latest_resume, nav, page_header, pills, require_login,
    start_interview, upload_prompt,
)


def _skill_row(label_html: str, by_type: dict | None, kind: str, empty_text: str) -> None:
    """One "✓ Matched"/"✗ Missing" row of pills. "Software & tools"/"Technical skills"
    subheadings are shown only when BOTH groups are non-empty; otherwise the pills run
    together with no label."""
    st.markdown(label_html, unsafe_allow_html=True)
    by_type = by_type or {}
    software = by_type.get("software") or []
    technical = by_type.get("technical") or []
    if not software and not technical:
        st.caption(empty_text)
        return
    if software and technical:
        st.caption("Software & tools")
        pills(software, kind)
        st.caption("Technical skills")
        pills(technical, kind)
    else:
        pills(software + technical, kind)


def _pill_html(items: list[str], kind: str) -> str:
    return " ".join(f'<span class="g2k-pill g2k-{kind}">{html.escape(display_skill(i))}</span>' for i in items)


def _other_skills_group(title: str, matched: list[str], missing: list[str]) -> None:
    st.markdown(f'<div style="font-weight:700; font-size:0.95rem; margin-bottom:0.4rem;">{html.escape(title)}</div>',
                unsafe_allow_html=True)
    if matched:
        st.markdown(
            '<div style="margin-bottom:0.75rem;"><span style="color:#166534; font-weight:600;">'
            f'✓ Matched:</span> {_pill_html(matched, "match")}</div>',
            unsafe_allow_html=True,
        )
    if missing:
        st.markdown(
            '<div style="margin-bottom:0.75rem;"><span style="color:#92400E; font-weight:600;">'
            f'✗ Missing:</span> {_pill_html(missing, "missing")}</div>',
            unsafe_allow_html=True,
        )


def _bold_leading_skill(text: str, names: list[str]) -> str:
    """Escape `text`, bolding its leading soft-skill name (the model is asked to start the
    "soft_skills" sentence with it) if the text happens to start with one of `names`. Falls back
    to plain escaped text if no name matches, rather than guessing."""
    for name in sorted(names or [], key=len, reverse=True):
        label = display_skill(name)
        if text.lower().startswith(label.lower()):
            head, rest = text[:len(label)], text[len(label):]
            return (f'<strong style="font-weight:600; color:#0F172A;">{html.escape(head)}</strong>'
                    f'{html.escape(rest)}')
    return html.escape(text)


def _ai_insights(explanation: dict, soft_skill_names: list[str] | None = None) -> None:
    """The AI explanation as an always-visible card: a header, a summary line, one mini-card per
    missing skill (an amber pill, a "Why it matters"/"How to close the gap" pair side by side),
    and -- if the role also values soft skills -- a light grey callout at the bottom. Reuses the
    g2k-pill/g2k-missing styles from frontend/common.py."""
    with st.container(border=True, key="g2k_card_ai_insights"):
        st.markdown(
            '<div style="display:flex; justify-content:space-between; align-items:center;">'
            '<div style="display:flex; align-items:center; gap:0.5rem;">'
            '<span class="material-symbols-outlined" style="color:#0B3FB8; font-size:1.3rem;">'
            'auto_awesome</span>'
            '<span style="font-weight:600; font-size:1.05rem;">AI insights</span></div>'
            '<span style="color:#94A3B8; font-size:0.75rem;">Generated by AI</span></div>',
            unsafe_allow_html=True,
        )
        st.markdown(
            f'<div style="color:#64748B; font-size:0.9rem; margin-top:0.5rem; margin-bottom:1rem;">'
            f'{html.escape(explanation["summary"])}</div>',
            unsafe_allow_html=True,
        )
        missing_items = explanation.get("missing") or []
        if missing_items:
            cards = "".join(
                '<div style="border:1px solid #E2E8F0; border-radius:10px; padding:12px;">'
                f'<span class="g2k-pill g2k-missing">{html.escape(display_skill(item["skill"]))}</span>'
                '<div class="g2k-gap-grid">'
                '<div><div style="display:flex; align-items:center; gap:0.3rem; color:#64748B; '
                'font-size:0.75rem; font-weight:600; text-transform:uppercase; letter-spacing:0.04em;">'
                '<span class="material-symbols-outlined" style="font-size:16px;">target</span>'
                'Why it matters</div>'
                f'<div style="margin-top:0.3rem;">{html.escape(item["why"])}</div></div>'
                '<div style="background:#EFF6FF; border-radius:8px; padding:8px;">'
                '<div style="display:flex; align-items:center; gap:0.3rem; color:#0B3FB8; '
                'font-size:0.75rem; font-weight:600; text-transform:uppercase; letter-spacing:0.04em;">'
                '<span class="material-symbols-outlined" style="font-size:16px;">route</span>'
                'How to close the gap</div>'
                f'<div style="margin-top:0.3rem; color:#0B3FB8;">{html.escape(item["learn"])}</div>'
                '</div></div></div>'
                for item in missing_items
            )
            st.markdown(
                f'<div style="display:flex; flex-direction:column; gap:10px;">{cards}</div>',
                unsafe_allow_html=True,
            )
        if explanation.get("soft_skills"):
            st.markdown(
                '<div style="background:#F1F5F9; border-radius:10px; padding:0.75rem 1rem; '
                'margin-top:1rem; display:flex; gap:0.5rem; align-items:flex-start;">'
                '<span class="material-symbols-outlined" style="font-size:18px; color:#64748B; '
                'margin-top:0.1rem;">group</span>'
                f'<span style="font-size:0.85rem; color:#64748B;">'
                f'{_bold_leading_skill(explanation["soft_skills"], soft_skill_names)}</span></div>',
                unsafe_allow_html=True,
            )


def _spacer() -> None:
    st.markdown('<div style="height:1rem;"></div>', unsafe_allow_html=True)


require_login()
jid = st.session_state.get("selected_job_id")
if jid is None:
    st.info("Pick a job from Find a Job first.")
    if st.button("Back to jobs", key="sm_back_empty"):
        nav("find_job")
    st.stop()

resume = get_latest_resume()
if resume is None:
    upload_prompt("Upload your resume to see how your skills compare with this role.")

job = call("GET", f"/jobs/{jid}")
# UC008 step 8: explain=True (the default) generates the AI explanation as part of this same
# call, so there's no separate button/click for it.
with st.spinner("Checking your skill match..."):
    gap = call("POST", "/skill-gap", json={"resume_id": resume["id"], "job_id": jid})

if st.button("Back to job", key="sm_back", icon=":material/arrow_back:"):
    nav("job_details")

page_header("Skill Match Analysis", f"{job['title']} at {job['company']}")

# Summary: donut + match count + matched/missing pills, all in one card.
with st.container(border=True, key="g2k_card_skill_summary"):
    if gap["match_pct"] is None:
        st.info(gap["message"])
        # UC008 alt flow 3.1: no skills on the resume -- point the user at fixing that, not
        # just the skill/missing lists below, which would all be empty/unhelpful here.
        if not resume["skills"] and st.button("Go to Resume Upload", type="primary", key="sm_upload",
                                               icon=":material/upload_file:"):
            nav("resume")
    else:
        d_col, s_col = st.columns([1, 2], gap="medium", vertical_alignment="center")
        with d_col:
            st.plotly_chart(donut(gap["match_pct"], "Skill Match", height=150), use_container_width=True,
                            config={"displayModeBar": False})
        with s_col:
            total = len(gap["matched"]) + len(gap["missing"])
            if total:
                st.markdown(f"**{len(gap['matched'])} of {total} required skills matched**")
            _skill_row('<span style="color:#166534; font-weight:600;">✓ Matched</span>',
                       gap.get("matched_by_type"), "match", "None yet")
            _skill_row('<span style="color:#92400E; font-weight:600;">✗ Missing</span>',
                       gap.get("missing_by_type"), "missing", "None missing")

st.caption("Score is based on software and technical skills.")
_spacer()

has_soft = bool(gap.get("soft_skills_required"))
has_languages = bool(gap["matched_languages"] or gap["missing_languages"])
if has_soft or has_languages:
    with st.container(border=True, key="g2k_card_other_skills"):
        st.subheader("Other skills")
        if has_soft:
            soft_listed = set(gap.get("soft_skills_listed") or [])
            soft_missing = [s for s in gap["soft_skills_required"] if s not in soft_listed]
            _other_skills_group("Soft skills", gap.get("soft_skills_listed") or [], soft_missing)
        if has_soft and has_languages:
            st.markdown('<hr style="margin:0.75rem 0; border-color:#E5E7EB;">', unsafe_allow_html=True)
        if has_languages:
            _other_skills_group("Languages", gap["matched_languages"], gap["missing_languages"])
    _spacer()

if gap.get("explanation"):
    _ai_insights(gap["explanation"], gap.get("soft_skills_required"))
    _spacer()
elif gap.get("explanation_note"):
    # UC008 alt flow 8.1: the skill match itself is still shown above; only the explanation failed.
    st.warning(gap["explanation_note"])
    _spacer()

if st.button("Practise interview for this role", type="primary", key="sm_interview"):
    start_interview(jid)
