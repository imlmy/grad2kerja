import streamlit as st

from frontend.common import nav, page_header, require_login, score_label, score_tier, soft, type_tag


def _step_indicator(current: int, total: int) -> None:
    """Filled/empty dots for questions 1..total, replacing a plain progress bar."""
    dots = "".join(
        '<span style="display:inline-block; width:10px; height:10px; border-radius:50%; '
        f'margin:0 4px; background:{"#0B3FB8" if i <= current else "#E2E8F0"};"></span>'
        for i in range(total)
    )
    st.markdown(
        f'<div style="text-align:center;">{dots}</div>'
        f'<div style="text-align:center; color:#64748B; font-size:0.85rem; margin-top:0.4rem;">'
        f'Question {current + 1} of {total}</div>',
        unsafe_allow_html=True,
    )

require_login()
session = st.session_state.get("interview")
if not session:
    st.info("Start a mock interview from a job's page.")
    if st.button("Go to Find a Job", key="iv_empty"):
        nav("find_job")
    st.stop()

questions = session["questions"]
total = len(questions)
answers = st.session_state.setdefault("interview_answers", {})
idx = st.session_state.get("q_index", 0)

if st.button("Back", key="iv_back", icon=":material/arrow_back:"):
    # Answers already submitted are saved server-side regardless of navigation.
    st.session_state["selected_job_id"] = session["job_id"]
    nav("job_details")

st.caption(f"Practising for: {session['job_title']} at {session.get('company') or ''}".upper())
page_header("Mock Interview Session")

if idx == 0:
    st.info(
        "Practice questions only. These questions are generated by AI based on the job listing "
        "and your resume to help you prepare. They are not provided by the employer and may not "
        "be asked in the actual interview."
    )

if idx >= total:
    st.success("Interview complete. Review your feedback report.")
    if st.button("View feedback report", type="primary", key="iv_report"):
        st.session_state["report_session_id"] = session["id"]
        nav("feedback_report")
    st.stop()

_step_indicator(idx, total)
question = questions[idx]
qid = question["id"]

with st.container(border=True):
    if question.get("type"):
        st.markdown(type_tag(question["type"]), unsafe_allow_html=True)
    st.markdown(f"**{question['question']}**")

if qid in answers:
    result = answers[qid]
    with st.container(border=True):
        st.caption("Your answer")
        st.write(result["answer"])
    with st.container(border=True):
        st.caption("AI interview feedback")
        st.markdown(
            f'<div class="g2k-score g2k-text-{score_tier(result["score"] * 10)}">'
            f'{result["score"]}<span> / 10</span></div>',
            unsafe_allow_html=True,
        )
        st.write(f"**{score_label(result['score'])}**")
        st.write(f"**Done well:** {result['strengths']}")
        st.write(f"**To improve:** {result['improvements']}")
    last = idx + 1 >= total
    if st.button("Finish interview" if last else "Next question", type="primary", key=f"next_{qid}"):
        st.session_state["q_index"] = idx + 1
        st.rerun()
else:
    text_key = f"text_{qid}"
    audio_key = f"audio_{qid}"
    attempted_key = f"transcribe_attempted_{qid}"
    transcript_key = f"transcript_text_{qid}"

    audio = st.audio_input("🎙 Record your answer", key=audio_key)
    if audio is not None and st.session_state.get(attempted_key) != audio.file_id:
        # A new recording -- transcribe it now so the text area below shows it for review
        # before the candidate submits, rather than submitting the raw audio blind.
        with st.spinner("Transcribing your recording..."):
            transcript, err = soft(
                "POST", "/interviews/transcribe",
                files={"audio": ("answer.wav", audio.getvalue(), "audio/wav")},
            )
        st.session_state[attempted_key] = audio.file_id
        if transcript:
            st.session_state[text_key] = transcript["text"]
            st.session_state[transcript_key] = transcript["text"]
        else:
            st.warning(f"Couldn't transcribe your recording ({err}). Please type your answer instead.")
            st.session_state.pop(transcript_key, None)

    text = st.text_area(
        "Your answer",
        placeholder="Type your answer here, or record it above -- review the transcript before submitting.",
        height=160, key=text_key,
    )
    word_count = len(text.split())
    st.caption(f"{word_count} words")

    if st.button("Submit answer", type="primary", key=f"submit_{qid}"):
        if not text.strip():
            st.warning("Type an answer or record one before submitting.")
            st.stop()
        # transcribed is only True if transcription succeeded for this recording AND the
        # submitted text still matches it verbatim -- an edited transcript, or one that failed
        # and was typed instead, is not "transcribed".
        transcript_text = st.session_state.get(transcript_key)
        transcribed = transcript_text is not None and text.strip() == transcript_text.strip()
        result, err = soft(
            "POST", f"/interviews/{session['id']}/answers",
            json={"question_id": qid, "text": text.strip(), "transcribed": transcribed},
        )
        if result is None:
            st.error(f"Couldn't evaluate your answer ({err}). Your answer is still here -- try submitting again.")
        else:
            answers[qid] = result
            st.rerun()
